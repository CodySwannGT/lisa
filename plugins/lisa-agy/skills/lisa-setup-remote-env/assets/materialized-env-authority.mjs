#!/usr/bin/env node
/**
 * Fail-closed authority for Lisa's materialized remote environment.
 *
 * SessionStart sources secret-bearing shell text, so it must first prove that
 * the path still has the exact type, mode, owner, and writer format Lisa owns.
 * This asset is self-contained because a freshly cloned remote host has no
 * plugin module graph yet.
 * @module materialized-env-authority
 */
import { lstatSync, readFileSync, realpathSync } from "node:fs";
import { dirname, isAbsolute, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const HEADER = [
  "# Generated by lisa-secrets-access. Contains secret values.",
  "# Do not print, inspect, summarize, commit, or copy this file.",
];
const SAFE_NAMESPACE = /^[A-Za-z0-9][A-Za-z0-9._-]*$/u;
const EXPORT_LINE = /^export ([A-Za-z_]\w*)='(.*)'$/u;
const AUTHORITY_REFUSAL = 77;

/**
 * Decide whether both materialized filesystem objects belong to this user.
 * @param {{directoryUid: number, expectedUid: number, fileUid: number}} facts
 *   Immutable owner identities.
 * @returns {boolean} Whether both objects have the expected owner.
 */
export function materializedOwnersMatch(facts) {
  return (
    facts.directoryUid === facts.expectedUid &&
    facts.fileUid === facts.expectedUid
  );
}

/**
 * Create the pure filesystem authority decision around one owner predicate.
 * @param {(facts: object) => boolean} ownersMatch Owner authority.
 * @returns {(facts: object) => {accepted: boolean, reason?: string}} Verdict.
 */
export function createMaterializedEnvAuthority(ownersMatch) {
  return facts => {
    if (facts.directoryType === "symlink" || facts.fileType === "symlink") {
      return { accepted: false, reason: "materialized environment symlink" };
    }
    if (facts.directoryType !== "directory") {
      return {
        accepted: false,
        reason: "materialized environment directory type mismatch",
      };
    }
    if (facts.fileType !== "file") {
      return {
        accepted: false,
        reason: "materialized environment regular file type mismatch",
      };
    }
    if (facts.directoryMode !== 0o700) {
      return {
        accepted: false,
        reason: "materialized environment directory mode is not 0700",
      };
    }
    if (facts.fileMode !== 0o600) {
      return {
        accepted: false,
        reason: "materialized environment file mode is not 0600",
      };
    }
    if (!ownersMatch(facts.ownership)) {
      return {
        accepted: false,
        reason: "materialized environment file ownership mismatch",
      };
    }
    return { accepted: true };
  };
}

export const validateMaterializedEnvAuthority = createMaterializedEnvAuthority(
  materializedOwnersMatch
);

/**
 * Identify one lstat result without following a symbolic link.
 * @param {import("node:fs").Stats} stat Immutable lstat observation.
 * @returns {"symlink" | "directory" | "file" | "other"} Object kind.
 */
function statType(stat) {
  if (stat.isSymbolicLink()) return "symlink";
  if (stat.isDirectory()) return "directory";
  if (stat.isFile()) return "file";
  return "other";
}

/**
 * Capture the complete immutable authority decision before reading bytes.
 * @param {string} valuesFile Absolute materialized artifact path.
 * @param {object} dependencies Injected filesystem and identity boundary.
 * @returns {Readonly<object>} Frozen authority facts.
 */
function authorityFacts(valuesFile, dependencies) {
  const expectedUid = dependencies.getuid();
  const directory = dependencies.lstat(dirname(valuesFile));
  const file = dependencies.lstat(valuesFile);
  const ownership = Object.freeze({
    directoryUid: directory.uid,
    expectedUid,
    fileUid: file.uid,
  });
  return Object.freeze({
    directoryMode: directory.mode & 0o777,
    directoryType: statType(directory),
    directoryUid: directory.uid,
    expectedUid,
    fileMode: file.mode & 0o777,
    fileType: statType(file),
    fileUid: file.uid,
    ownership,
  });
}

/**
 * Prove text is exactly the sorted, newline-terminated Lisa writer format.
 * @param {string} text Candidate shell artifact content.
 * @returns {boolean} Whether the complete artifact matches the writer format.
 */
function materializedFormatValid(text) {
  if (typeof text !== "string" || !text.endsWith("\n")) return false;
  const lines = text.split("\n");
  lines.pop();
  if (lines[0] !== HEADER[0] || lines[1] !== HEADER[1]) return false;
  const names = [];
  for (const line of lines.slice(2)) {
    const match = EXPORT_LINE.exec(line);
    if (!match || match[2].replaceAll("'\\''", "").includes("'")) {
      return false;
    }
    names.push(match[1]);
  }
  return names.every((name, index) => index === 0 || names[index - 1] < name);
}

/**
 * Read the configured safe namespace and resolve its exact values artifact.
 * @param {string} configFile Absolute project configuration path.
 * @param {string} configRoot Absolute per-user configuration root.
 * @param {object} dependencies Injected filesystem boundary.
 * @returns {string} Absolute materialized values path.
 */
function valuesFileFromConfig(configFile, configRoot, dependencies) {
  let config = {};
  try {
    config = JSON.parse(dependencies.readFile(configFile, "utf8"));
  } catch (error) {
    if (error?.code !== "ENOENT") throw new Error("configuration is invalid");
  }
  if (!config || typeof config !== "object" || Array.isArray(config)) {
    throw new Error("configuration is invalid");
  }
  const secrets = config.secrets ?? {};
  if (!secrets || typeof secrets !== "object" || Array.isArray(secrets)) {
    throw new Error("configuration secrets are invalid");
  }
  const namespace = secrets.namespace ?? "lisa";
  if (
    typeof namespace !== "string" ||
    namespace === ".." ||
    !SAFE_NAMESPACE.test(namespace)
  ) {
    throw new Error("unsafe materialized environment namespace");
  }
  if (!isAbsolute(configRoot)) {
    throw new Error("materialized environment config root is not absolute");
  }
  return join(configRoot, namespace, "secrets.env");
}

/**
 * Convert a caught failure into a bounded, value-free reason.
 * @param {unknown} error Refusal caught at the CLI boundary.
 * @returns {string} Public diagnostic reason without artifact content.
 */
function refusalReason(error) {
  if (error?.code === "ENOENT") return "file is missing";
  if (error?.code === "EACCES") return "file is unreadable";
  if (error instanceof Error && error.message.startsWith("materialized ")) {
    return error.message;
  }
  if (error instanceof Error && error.message.startsWith("unsafe ")) {
    return error.message;
  }
  if (error instanceof Error && error.message.startsWith("configuration ")) {
    return error.message;
  }
  return "authority check failed";
}

/** Default synchronous boundary; injection is reserved for executable tests. */
const DEFAULT_DEPENDENCIES = Object.freeze({
  getuid: () => (typeof process.getuid === "function" ? process.getuid() : -1),
  lstat: lstatSync,
  readFile: readFileSync,
  writeError: diagnostic => process.stderr.write(diagnostic),
  writeOutput: output => process.stdout.write(output),
});

/**
 * Validate one materialized file, or resolve it from the project config.
 * @param {readonly string[]} argv Direct file or `--resolve` arguments.
 * @param {object} [injected] Test-owned filesystem and diagnostic boundary.
 * @returns {number} Zero only after complete authority and format validation.
 */
export function runMaterializedEnvAuthorityCli(argv, injected = {}) {
  const dependencies = { ...DEFAULT_DEPENDENCIES, ...injected };
  try {
    const resolving = argv[0] === "--resolve";
    if ((!resolving && argv.length !== 1) || (resolving && argv.length !== 3)) {
      throw new Error("materialized environment arguments are invalid");
    }
    const valuesFile = resolving
      ? valuesFileFromConfig(argv[1], argv[2], dependencies)
      : argv[0];
    if (!isAbsolute(valuesFile)) {
      throw new Error("materialized environment path is not absolute");
    }
    const facts = authorityFacts(valuesFile, dependencies);
    const decision = validateMaterializedEnvAuthority(facts);
    if (!decision.accepted) throw new Error(decision.reason);
    const text = dependencies.readFile(valuesFile, "utf8");
    if (!materializedFormatValid(text)) {
      throw new Error("materialized environment format is invalid");
    }
    if (resolving) dependencies.writeOutput(`${valuesFile}\n`);
    return 0;
  } catch (error) {
    const reason = refusalReason(error);
    dependencies.writeError(`Lisa materialized environment ${reason}\n`);
    return AUTHORITY_REFUSAL;
  }
}

/**
 * Decide whether this module is the process entrypoint.
 * @param {string} moduleUrl Current module URL.
 * @param {string | undefined} argv1 Invoked script path, when present.
 * @returns {boolean} Whether the CLI driver must run.
 */
function invokedAsScript(moduleUrl, argv1 = process.argv[1]) {
  return (
    Boolean(argv1) &&
    realpathSync(resolve(argv1)) === realpathSync(fileURLToPath(moduleUrl))
  );
}

if (invokedAsScript(import.meta.url)) {
  process.exitCode = runMaterializedEnvAuthorityCli(process.argv.slice(2));
}
